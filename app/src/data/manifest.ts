import { z } from 'zod';
import type { PuffDefinition } from '../domain/types.ts';

const unit = z.number().min(0).max(1);

const puffSchema = z.object({
  id: z.string().min(1),
  model: z.string().min(1),
  modelSlug: z.string().min(1),
  flavor: z.string().min(1),
  puffs: z.number().int().positive().nullable(),
  images: z.object({ thumb: z.string(), detail: z.string() }),
  quality: z.object({ integrity: z.number(), resolution: z.number() }),
  color: z.string().regex(/^#[0-9a-f]{6}$/i),
  nozzle: z.object({ x: unit, y: unit }),
  bbox: z.object({ x: unit, y: unit, w: unit, h: unit }),
});

const manifestSchema = z.object({
  version: z.literal(1),
  count: z.number().int(),
  puffs: z.array(puffSchema),
});

export const MANIFEST_PATH = 'puffs/manifest.json';

/** Resolves a manifest-relative asset path against the app's base URL. */
export function assetUrl(path: string): string {
  return `${import.meta.env.BASE_URL}${path}`;
}

/** Fetches and validates the puff catalog generated by `npm run assets`. */
export async function loadManifest(fetcher: typeof fetch = fetch): Promise<PuffDefinition[]> {
  const response = await fetcher(assetUrl(MANIFEST_PATH));
  if (!response.ok) {
    throw new Error(`Manifeste introuvable (${response.status}). Lance « npm run assets ».`);
  }
  return manifestSchema.parse(await response.json()).puffs;
}
